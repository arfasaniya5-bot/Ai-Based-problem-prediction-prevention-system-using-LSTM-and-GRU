from datetime import datetime, timezone
from sqlalchemy import (
    BigInteger,
    Boolean,
    Column,
    DateTime,
    Float,
    ForeignKey,
    Integer,
    String,
    Text,
)
from sqlalchemy.orm import declarative_base, relationship

Base = declarative_base()


class Device(Base):
    """Storage drive entity tracking identity and operational status."""

    __tablename__ = "devices"

    id = Column(Integer, primary_key=True, index=True)
    serial_number = Column(String(64), unique=True, index=True, nullable=False)
    model = Column(String(64), index=True, nullable=True)
    capacity_bytes = Column(BigInteger, nullable=True)
    status = Column(String(32), default="HEALTHY", nullable=False)  # HEALTHY, WARNING, CRITICAL, FAILED
    first_seen = Column(DateTime, default=lambda: datetime.now(timezone.utc), nullable=False)
    last_seen = Column(DateTime, default=lambda: datetime.now(timezone.utc), nullable=False)

    # Relationships
    readings = relationship("TelemetryReading", back_populates="device", cascade="all, delete-orphan")
    predictions = relationship("PredictionRecord", back_populates="device", cascade="all, delete-orphan")
    alerts = relationship("AlertRecord", back_populates="device", cascade="all, delete-orphan")


class TelemetryReading(Base):
    """Recorded daily SMART observations for a storage drive."""

    __tablename__ = "telemetry_readings"

    id = Column(Integer, primary_key=True, index=True)
    device_id = Column(Integer, ForeignKey("devices.id", ondelete="CASCADE"), nullable=False, index=True)
    timestamp = Column(DateTime, default=lambda: datetime.now(timezone.utc), nullable=False, index=True)

    # SMART raw counters
    smart_1_raw = Column(Float, nullable=True)
    smart_4_raw = Column(Float, nullable=True)
    smart_5_raw = Column(Float, nullable=True)
    smart_7_raw = Column(Float, nullable=True)
    smart_9_raw = Column(Float, nullable=True)
    smart_12_raw = Column(Float, nullable=True)
    smart_187_raw = Column(Float, nullable=True)
    smart_188_raw = Column(Float, nullable=True)
    smart_194_raw = Column(Float, nullable=True)
    smart_197_raw = Column(Float, nullable=True)
    smart_198_raw = Column(Float, nullable=True)

    device = relationship("Device", back_populates="readings")


class PredictionRecord(Base):
    """Historical inference record generated by the predictive AI models."""

    __tablename__ = "prediction_records"

    id = Column(Integer, primary_key=True, index=True)
    device_id = Column(Integer, ForeignKey("devices.id", ondelete="SET NULL"), nullable=True, index=True)
    timestamp = Column(DateTime, default=lambda: datetime.now(timezone.utc), nullable=False, index=True)

    model_name = Column(String(64), nullable=False)
    model_version = Column(String(32), nullable=False)
    prediction_class = Column(Integer, nullable=False)  # 0: Healthy, 1: Failure Predicted
    risk_score = Column(Float, nullable=False)         # Model sigmoid probability in [0.0, 1.0]
    risk_level = Column(String(32), nullable=False)     # LOW, MODERATE, CRITICAL
    threshold = Column(Float, nullable=False)          # Configured decision threshold (e.g. 0.50)
    horizon_days = Column(Integer, default=2, nullable=False)
    input_sequence_length = Column(Integer, default=3, nullable=False)
    status = Column(String(32), default="SUCCESS", nullable=False)

    device = relationship("Device", back_populates="predictions")
    alerts = relationship("AlertRecord", back_populates="prediction", cascade="all, delete-orphan")


class AlertRecord(Base):
    """Actionable failure prevention alert and maintenance recommendation."""

    __tablename__ = "alert_records"

    id = Column(Integer, primary_key=True, index=True)
    prediction_id = Column(Integer, ForeignKey("prediction_records.id", ondelete="CASCADE"), nullable=False, index=True)
    device_id = Column(Integer, ForeignKey("devices.id", ondelete="SET NULL"), nullable=True, index=True)
    timestamp = Column(DateTime, default=lambda: datetime.now(timezone.utc), nullable=False, index=True)

    severity = Column(String(32), nullable=False)  # INFO, WARNING, CRITICAL
    recommendation = Column(Text, nullable=False)
    acknowledged = Column(Boolean, default=False, nullable=False)
    acknowledged_at = Column(DateTime, nullable=True)

    prediction = relationship("PredictionRecord", back_populates="alerts")
    device = relationship("Device", back_populates="alerts")


class ApiLog(Base):
    """Audit log of API requests and processing status."""

    __tablename__ = "api_logs"

    id = Column(Integer, primary_key=True, index=True)
    timestamp = Column(DateTime, default=lambda: datetime.now(timezone.utc), nullable=False, index=True)
    endpoint = Column(String(128), nullable=False)
    status_code = Column(Integer, nullable=False)
    response_time_ms = Column(Float, nullable=False)
    error_message = Column(Text, nullable=True)
